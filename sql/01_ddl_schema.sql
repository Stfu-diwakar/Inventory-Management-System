-- 13. DATABASE TRIGGERS
-- ============================================================================

-- Trigger 1: Automatic Audit Log on Product Price Changes
CREATE OR REPLACE TRIGGER TRG_AUDIT_PRODUCT_CHANGES
AFTER UPDATE OF unit_price, cost_price ON PRODUCTS
FOR EACH ROW
BEGIN
    INSERT INTO AUDIT_LOGS (table_name, action_type, record_id, details)
    VALUES (
        'PRODUCTS',
        'UPDATE',
        TO_CHAR(:NEW.product_id),
        'Price updated for SKU ' || :NEW.sku || 
        '. Old Unit Price: ' || :OLD.unit_price || ', New Unit Price: ' || :NEW.unit_price ||
        '. Old Cost Price: ' || :OLD.cost_price || ', New Cost Price: ' || :NEW.cost_price
    );
END;
/

-- Trigger 2: Automatic Audit Log on Product Deletion
CREATE OR REPLACE TRIGGER TRG_AUDIT_PRODUCT_DELETE
BEFORE DELETE ON PRODUCTS
FOR EACH ROW
BEGIN
    INSERT INTO AUDIT_LOGS (table_name, action_type, record_id, details)
    VALUES (
        'PRODUCTS',
        'DELETE',
        TO_CHAR(:OLD.product_id),
        'Product removed: ' || :OLD.product_name || ' (SKU: ' || :OLD.sku || ')'
    );
END;
/

COMMIT;
