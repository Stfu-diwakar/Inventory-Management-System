-- ----------------------------------------------------------------------------
-- 1. DROP EXISTING OBJECTS (CLEANUP FOR IDEMPOTENT RUNS)
-- ----------------------------------------------------------------------------
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'AUDIT_LOGS', 'STOCK_TRANSACTIONS', 'ORDER_ITEMS', 'ORDERS', 
        'INVENTORY', 'PRODUCTS', 'WAREHOUSES', 'SUPPLIERS', 'CUSTOMERS', 'CATEGORIES'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;

    FOR v IN (SELECT view_name FROM user_views WHERE view_name IN (
        'VW_PRODUCT_STOCK_SUMMARY', 'VW_LOW_STOCK_ALERTS', 
        'VW_SALES_ANALYTICS', 'VW_WAREHOUSE_OCCUPANCY', 'VW_SUPPLIER_RATINGS'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP VIEW ' || v.view_name;
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 2. TABLE: CATEGORIES
-- ----------------------------------------------------------------------------
CREATE TABLE CATEGORIES (
    category_id     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    category_name   VARCHAR2(100) NOT NULL CONSTRAINT uq_category_name UNIQUE,
    description     VARCHAR2(255),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 3. TABLE: SUPPLIERS
-- ----------------------------------------------------------------------------
CREATE TABLE SUPPLIERS (
    supplier_id     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    supplier_name   VARCHAR2(150) NOT NULL,
    contact_person  VARCHAR2(100),
    email           VARCHAR2(100) CONSTRAINT uq_supplier_email UNIQUE,
    phone           VARCHAR2(25),
    address         VARCHAR2(255),
    city            VARCHAR2(50),
    rating          NUMBER(3,1) DEFAULT 4.5 CONSTRAINT chk_supplier_rating CHECK (rating >= 1.0 AND rating <= 5.0),
    status          VARCHAR2(20) DEFAULT 'ACTIVE' CONSTRAINT chk_supplier_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 4. TABLE: WAREHOUSES
-- ----------------------------------------------------------------------------
CREATE TABLE WAREHOUSES (
    warehouse_id    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    warehouse_name  VARCHAR2(100) NOT NULL CONSTRAINT uq_warehouse_name UNIQUE,
    location        VARCHAR2(150) NOT NULL,
    capacity        NUMBER NOT NULL CONSTRAINT chk_wh_capacity CHECK (capacity > 0),
    manager_name    VARCHAR2(100),
    contact_number  VARCHAR2(25),
    status          VARCHAR2(20) DEFAULT 'ACTIVE' CONSTRAINT chk_wh_status CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'CLOSED')),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 5. TABLE: CUSTOMERS
-- ----------------------------------------------------------------------------
CREATE TABLE CUSTOMERS (
    customer_id     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    customer_name   VARCHAR2(150) NOT NULL,
    email           VARCHAR2(100) CONSTRAINT uq_customer_email UNIQUE,
    phone           VARCHAR2(25),
    address         VARCHAR2(255),
    city            VARCHAR2(50),
    customer_type   VARCHAR2(20) DEFAULT 'RETAIL' CONSTRAINT chk_cust_type CHECK (customer_type IN ('RETAIL', 'WHOLESALE', 'CORPORATE')),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 6. TABLE: PRODUCTS
-- ----------------------------------------------------------------------------
CREATE TABLE PRODUCTS (
    product_id      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    sku             VARCHAR2(50) NOT NULL CONSTRAINT uq_product_sku UNIQUE,
    product_name    VARCHAR2(150) NOT NULL,
    category_id     NUMBER CONSTRAINT fk_prod_category REFERENCES CATEGORIES(category_id) ON DELETE SET NULL,
    supplier_id     NUMBER CONSTRAINT fk_prod_supplier REFERENCES SUPPLIERS(supplier_id) ON DELETE SET NULL,
    cost_price      NUMBER(10,2) NOT NULL CONSTRAINT chk_prod_cost CHECK (cost_price >= 0),
    unit_price      NUMBER(10,2) NOT NULL CONSTRAINT chk_prod_price CHECK (unit_price >= 0),
    reorder_level   NUMBER DEFAULT 10 CONSTRAINT chk_prod_reorder CHECK (reorder_level >= 0),
    unit_of_measure VARCHAR2(20) DEFAULT 'PCS',
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_price_gte_cost CHECK (unit_price >= cost_price)
);

-- ----------------------------------------------------------------------------
-- 7. TABLE: INVENTORY (STOCK PER WAREHOUSE)
-- ----------------------------------------------------------------------------
CREATE TABLE INVENTORY (
    inventory_id     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    product_id       NUMBER NOT NULL CONSTRAINT fk_inv_product REFERENCES PRODUCTS(product_id) ON DELETE CASCADE,
    warehouse_id     NUMBER NOT NULL CONSTRAINT fk_inv_warehouse REFERENCES WAREHOUSES(warehouse_id) ON DELETE CASCADE,
    quantity_on_hand NUMBER DEFAULT 0 NOT NULL CONSTRAINT chk_inv_qty CHECK (quantity_on_hand >= 0),
    last_updated     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_product_warehouse UNIQUE (product_id, warehouse_id)
);

-- ----------------------------------------------------------------------------
-- 8. TABLE: ORDERS (SALES ORDERS)
-- ----------------------------------------------------------------------------
CREATE TABLE ORDERS (
    order_id        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    order_number    VARCHAR2(50) NOT NULL CONSTRAINT uq_order_number UNIQUE,
    customer_id     NUMBER NOT NULL CONSTRAINT fk_orders_customer REFERENCES CUSTOMERS(customer_id),
    order_date      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    total_amount    NUMBER(12,2) DEFAULT 0.00 NOT NULL CONSTRAINT chk_order_total CHECK (total_amount >= 0),
    tax_amount      NUMBER(10,2) DEFAULT 0.00 NOT NULL CONSTRAINT chk_order_tax CHECK (tax_amount >= 0),
    status          VARCHAR2(20) DEFAULT 'COMPLETED' CONSTRAINT chk_order_status CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'CANCELLED')),
    payment_method  VARCHAR2(30) DEFAULT 'CREDIT_CARD' CONSTRAINT chk_order_pay CHECK (payment_method IN ('CASH', 'CREDIT_CARD', 'BANK_TRANSFER', 'UPI')),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 9. TABLE: ORDER_ITEMS
-- ----------------------------------------------------------------------------
CREATE TABLE ORDER_ITEMS (
    order_item_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    order_id        NUMBER NOT NULL CONSTRAINT fk_oi_order REFERENCES ORDERS(order_id) ON DELETE CASCADE,
    product_id      NUMBER NOT NULL CONSTRAINT fk_oi_product REFERENCES PRODUCTS(product_id),
    warehouse_id    NUMBER NOT NULL CONSTRAINT fk_oi_warehouse REFERENCES WAREHOUSES(warehouse_id),
    quantity        NUMBER NOT NULL CONSTRAINT chk_oi_qty CHECK (quantity > 0),
    unit_price      NUMBER(10,2) NOT NULL CONSTRAINT chk_oi_unitprice CHECK (unit_price >= 0),
    subtotal        NUMBER(12,2) NOT NULL CONSTRAINT chk_oi_subtotal CHECK (subtotal >= 0)
);

-- ----------------------------------------------------------------------------
-- 10. TABLE: STOCK_TRANSACTIONS (AUDIT & MOVEMENT LEDGER)
-- ----------------------------------------------------------------------------
CREATE TABLE STOCK_TRANSACTIONS (
    transaction_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    product_id       NUMBER NOT NULL CONSTRAINT fk_trans_product REFERENCES PRODUCTS(product_id) ON DELETE CASCADE,
    warehouse_id     NUMBER NOT NULL CONSTRAINT fk_trans_warehouse REFERENCES WAREHOUSES(warehouse_id) ON DELETE CASCADE,
    transaction_type VARCHAR2(25) NOT NULL CONSTRAINT chk_trans_type CHECK (
        transaction_type IN ('STOCK_IN', 'STOCK_OUT', 'TRANSFER_IN', 'TRANSFER_OUT', 'ADJUSTMENT')
    ),
    quantity         NUMBER NOT NULL,
    reference_id     VARCHAR2(100),
    notes            VARCHAR2(255),
    performed_by     VARCHAR2(100) DEFAULT USER,
    transaction_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 11. TABLE: AUDIT_LOGS (SYSTEM ACTIVITY LOG)
-- ----------------------------------------------------------------------------
CREATE TABLE AUDIT_LOGS (
    log_id          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    table_name      VARCHAR2(50) NOT NULL,
    action_type     VARCHAR2(20) NOT NULL CONSTRAINT chk_audit_action CHECK (action_type IN ('INSERT', 'UPDATE', 'DELETE')),
    record_id       VARCHAR2(50),
    performed_by    VARCHAR2(100) DEFAULT USER,
    action_date     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    details         VARCHAR2(500)
);

-- ============================================================================
-- 12. DATABASE VIEWS (FOR ANALYTICS & REPORTING)
-- ============================================================================

-- View 1: Product Stock Summary with Valuation
CREATE OR REPLACE VIEW VW_PRODUCT_STOCK_SUMMARY AS
SELECT 
    p.product_id,
    p.sku,
    p.product_name,
    c.category_name,
    s.supplier_name,
    p.cost_price,
    p.unit_price,
    ROUND((p.unit_price - p.cost_price), 2) AS profit_margin,
    ROUND(((p.unit_price - p.cost_price) / NULLIF(p.unit_price, 0)) * 100, 2) AS margin_percentage,
    p.reorder_level,
    NVL(SUM(i.quantity_on_hand), 0) AS total_stock,
    ROUND(NVL(SUM(i.quantity_on_hand), 0) * p.cost_price, 2) AS inventory_valuation,
    ROUND(NVL(SUM(i.quantity_on_hand), 0) * p.unit_price, 2) AS retail_valuation,
    CASE 
        WHEN NVL(SUM(i.quantity_on_hand), 0) = 0 THEN 'OUT_OF_STOCK'
        WHEN NVL(SUM(i.quantity_on_hand), 0) <= p.reorder_level THEN 'LOW_STOCK'
        ELSE 'HEALTHY'
    END AS stock_status
FROM PRODUCTS p
LEFT JOIN CATEGORIES c ON p.category_id = c.category_id
LEFT JOIN SUPPLIERS s ON p.supplier_id = s.supplier_id
LEFT JOIN INVENTORY i ON p.product_id = i.product_id
GROUP BY 
    p.product_id, p.sku, p.product_name, c.category_name, 
    s.supplier_name, p.cost_price, p.unit_price, p.reorder_level;

-- View 2: Low Stock Alerts
CREATE OR REPLACE VIEW VW_LOW_STOCK_ALERTS AS
SELECT 
    product_id,
    sku,
    product_name,
    category_name,
    supplier_name,
    total_stock,
    reorder_level,
    (reorder_level - total_stock) AS units_needed,
    cost_price,
    stock_status
FROM VW_PRODUCT_STOCK_SUMMARY
WHERE stock_status IN ('LOW_STOCK', 'OUT_OF_STOCK');

-- View 3: Warehouse Occupancy & Capacity Utilization
CREATE OR REPLACE VIEW VW_WAREHOUSE_OCCUPANCY AS
SELECT 
    w.warehouse_id,
    w.warehouse_name,
    w.location,
    w.capacity,
    NVL(SUM(i.quantity_on_hand), 0) AS current_stock_units,
    COUNT(DISTINCT i.product_id) AS distinct_products_stored,
    ROUND((NVL(SUM(i.quantity_on_hand), 0) / NULLIF(w.capacity, 0)) * 100, 2) AS utilization_percentage,
    w.status
FROM WAREHOUSES w
LEFT JOIN INVENTORY i ON w.warehouse_id = i.warehouse_id
GROUP BY w.warehouse_id, w.warehouse_name, w.location, w.capacity, w.status;

-- View 4: Sales Performance & Customer Analytics
CREATE OR REPLACE VIEW VW_SALES_ANALYTICS AS
SELECT 
    o.order_id,
    o.order_number,
    o.order_date,
    c.customer_name,
    c.customer_type,
    o.total_amount,
    o.tax_amount,
    o.payment_method,
    o.status,
    COUNT(oi.order_item_id) AS items_count,
    NVL(SUM(oi.quantity), 0) AS total_units_sold
FROM ORDERS o
JOIN CUSTOMERS c ON o.customer_id = c.customer_id
LEFT JOIN ORDER_ITEMS oi ON o.order_id = oi.order_id
GROUP BY 
    o.order_id, o.order_number, o.order_date, c.customer_name, 
    c.customer_type, o.total_amount, o.tax_amount, o.payment_method, o.status;

-- View 5: Supplier Ratings & Supply Summary
CREATE OR REPLACE VIEW VW_SUPPLIER_RATINGS AS
SELECT 
    s.supplier_id,
    s.supplier_name,
    s.city,
    s.rating,
    s.status,
    COUNT(DISTINCT p.product_id) AS total_products_supplied,
    NVL(SUM(i.quantity_on_hand), 0) AS total_stock_held,
    ROUND(NVL(SUM(i.quantity_on_hand * p.cost_price), 0), 2) AS total_supplied_valuation
FROM SUPPLIERS s
LEFT JOIN PRODUCTS p ON s.supplier_id = p.supplier_id
LEFT JOIN INVENTORY i ON p.product_id = i.product_id
GROUP BY s.supplier_id, s.supplier_name, s.city, s.rating, s.status;

